import sys
from awsglue.transforms import *
from awsglue.utils import getResolvedOptions
from pyspark.context import SparkContext
from awsglue.context import GlueContext
from awsglue.job import Job
from awsgluedq.transforms import EvaluateDataQuality
from awsglue import DynamicFrame


def sparkSqlQuery(glueContext, query, mapping, transformation_ctx) -> DynamicFrame:
    for alias, frame in mapping.items():
        frame.toDF().createOrReplaceTempView(alias)
    result = spark.sql(query)
    return DynamicFrame.fromDF(result, glueContext, transformation_ctx)


args = getResolvedOptions(sys.argv, ["JOB_NAME"])
sc = SparkContext()
glueContext = GlueContext(sc)
spark = glueContext.spark_session
job = Job(glueContext)
job.init(args["JOB_NAME"], args)

# Default ruleset for Glue Data Quality, as generated by Glue Studio
DEFAULT_DATA_QUALITY_RULESET = """
    Rules = [
        ColumnCount > 0
    ]
"""

# Script generated for node Orders
Orders_node1 = glueContext.create_dynamic_frame.from_catalog(
    database="raw_db", table_name="orders", transformation_ctx="Orders_node1"
)

# Script generated for node Customers
Customers_node2 = glueContext.create_dynamic_frame.from_catalog(
    database="raw_db", table_name="customers", transformation_ctx="Customers_node2"
)

# Script generated for node Change Schema
ChangeSchema_node3 = ApplyMapping.apply(
    frame=Orders_node1,
    mappings=[
        ("customer_id", "long", "customer_id", "long"),
        ("amount", "string", "amount", "double"),
    ],
    transformation_ctx="ChangeSchema_node3",
)

# Script generated for node SQL Query
SqlQuery0 = """
select c.name, sum(o.amount) as total
from orders o join customers c on o.customer_id = cast(c.customer_id as bigint)
group by c.name
"""
SQLQuery_node4 = sparkSqlQuery(
    glueContext,
    query=SqlQuery0,
    mapping={"orders": ChangeSchema_node3, "customers": Customers_node2},
    transformation_ctx="SQLQuery_node4",
)

# Script generated for node Evaluate Data Quality
EvaluateDataQuality().process_rows(
    frame=SQLQuery_node4,
    ruleset=DEFAULT_DATA_QUALITY_RULESET,
    publishing_options={"dataQualityEvaluationContext": "orders_dq_rows"},
    additional_options={"dataQualityResultsPublishing.strategy": "BEST_EFFORT"},
)
EvaluateDataQuality.apply(
    frame=SQLQuery_node4,
    ruleset=DEFAULT_DATA_QUALITY_RULESET,
    publishing_options={"dataQualityEvaluationContext": "orders_dq"},
)

# Script generated for node Amazon S3
AmazonS3_node5 = glueContext.write_dynamic_frame.from_options(
    frame=SQLQuery_node4,
    connection_type="s3",
    format="glueparquet",
    connection_options={"path": "s3://curated/totals/", "partitionKeys": []},
    format_options={"compression": "snappy"},
    transformation_ctx="AmazonS3_node5",
)

job.commit()
